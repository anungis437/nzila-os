import { Card } from '@/components/primitives/Card'
import { SectionHeader } from '@/components/primitives/SectionHeader'
import { Badge } from '@/components/primitives/Badge'
import { ReportExportButton } from '@/components/reports/ReportExportButton'
import { fmtDateTime } from '@/lib/format'
import { getHqRepository } from '@/server/repository'
import { resolveOrgContext } from '@/lib/resolve-org'
import { assertCapability } from '@/lib/rbac'

export const dynamic = 'force-dynamic'

export default async function ReportsPage() {
  const ctx = await resolveOrgContext()
  assertCapability(ctx.role, 'export:report')

  const repo = getHqRepository()
  const reports = [
    { ...repo.weeklyCeoBrief(), tone: 'violet' as const },
    { ...repo.pipelineReview(), tone: 'sky' as const },
    { ...repo.dependencyTrend(), tone: 'amber' as const },
    { ...repo.monthlyPortfolioReview(), tone: 'emerald' as const },
  ]

  return (
    <div className="space-y-6">
      <SectionHeader
        eyebrow="Phase 17 · Reporting"
        title="Reports"
        description="Auto-generated by @nzila/hq-domain. These are the same artifacts that will be delivered weekly to the founder and monthly to the board."
      />

      {reports.map((r) => (
        <Card
          key={r.kind}
          title={r.title}
          description={r.summary}
          action={
            <div className="flex items-center gap-2">
              <Badge tone={r.tone}>{r.kind}</Badge>
              <span className="text-[11px] text-slate-500">
                generated {fmtDateTime(r.generatedAt)}
              </span>
              <ReportExportButton
                markdown={r.markdown}
                filename={`${r.kind}-${r.generatedAt.slice(0, 10)}.md`}
              />
            </div>
          }
        >
          {r.sections.length > 0 && (
            <div className="mb-4 space-y-3">
              {r.sections.map((s, i) => (
                <div key={i}>
                  <div className="text-xs font-semibold uppercase tracking-wider text-slate-500">
                    {s.heading}
                  </div>
                  <pre className="mt-1.5 whitespace-pre-wrap font-sans text-sm text-slate-700">
                    {s.body}
                  </pre>
                </div>
              ))}
            </div>
          )}
          <details className="rounded-md bg-slate-50">
            <summary className="cursor-pointer px-4 py-2 text-xs font-medium text-slate-600">
              Markdown source (copy into Slack / email / board deck)
            </summary>
            <pre className="overflow-x-auto px-4 pb-4 pt-2 text-xs text-slate-800">
              {r.markdown}
            </pre>
          </details>
        </Card>
      ))}
    </div>
  )
}
