"""
Management command: the platform migration that gives the database the defaults the Django models already apply.

Usage:
    python manage.py ue_model_defaults_sql --label=<label>               > db/migrations-platform/00NN_<label>.sql
    python manage.py ue_model_defaults_sql --label=<label> --rollback    > db/migrations-platform/00NN_<label>.rollback.sql

A Django model that gives a column a default writes that value on every INSERT. When the column has none, a row written by any other writer (a SQL
script, a raw INSERT, a service that is added later) either fails (NOT NULL) or stores something else, so one logical row differs by writer
(``ue_physical_parity`` reports it as DEFAULT_DIVERGES). Where Django is the only layer that declares the relation, the model's default is the
relation's own design and the database takes it over unchanged; nothing is invented. Run it against a database that already has the platform
migrations before it, so a column some other migration has already given a default is not listed.

Fail-closed: a column that already has a default keeps it, a column that already carries a comment is refused (the rollback finds what this migration
set by its tag), and a model default the migration cannot express as SQL stops the generator rather than being skipped.
"""
import json
import uuid
from decimal import Decimal

from django.apps import apps
from django.core.management.base import BaseCommand, CommandError
from django.db import connection
from django.db.models import NOT_PROVIDED
from django.utils import timezone

from core.management.commands.ue_physical_parity import CONTRIB_APPS, COMPUTED, Catalog, split_table, unbacked_default


def sql_default(table, field, column, written):
    """The SQL text of the default the model writes, in the form PostgreSQL stores it."""
    if written is COMPUTED:
        if field.default is uuid.uuid4:
            return "gen_random_uuid()"
        if field.default is timezone.now:
            return "now()"
        raise CommandError(f"{table}.{field.column}: the model default {field.default!r} has no SQL form")
    if isinstance(written, bool):
        return "true" if written else "false"
    if isinstance(written, (int, Decimal)):
        return str(written)
    if isinstance(written, str):
        return "'" + written.replace("'", "''") + "'"
    if isinstance(written, (dict, list, tuple)):
        if column["type"].endswith("[]"):
            if written:
                raise CommandError(f"{table}.{field.column}: a non-empty array default has no SQL form here")
            return f"ARRAY[]::{column['type']}"
        return "'" + json.dumps(written, sort_keys=True).replace("'", "''") + "'::jsonb"
    raise CommandError(f"{table}.{field.column}: the model default {written!r} has no SQL form")


def unbacked_defaults():
    """``(schema, table, column, sql)`` for every column whose model default the database lacks, in a stable order."""
    with connection.cursor() as cursor:
        catalog = Catalog(cursor)
    rows = {}
    for model in apps.get_models(include_auto_created=True):
        meta = model._meta
        if meta.proxy or meta.abstract or not meta.managed or meta.app_label in CONTRIB_APPS:
            continue
        schema, table = split_table(meta.db_table)
        physical = catalog.columns.get((schema, table))
        if physical is None:
            continue
        for field in meta.local_concrete_fields:
            column = physical.get(field.column)
            if column is None:
                continue
            written = unbacked_default(field, column)
            if written is NOT_PROVIDED:
                continue
            rows[(schema, table, field.column)] = sql_default(meta.db_table, field, column, written)
    return [(*key, sql) for key, sql in sorted(rows.items())]


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def forward(label, rows):
    tag = literal(f"platform-migration:{label}:default")
    values = ",\n".join(f"    ({literal(s)}, {literal(t)}, {literal(c)}, {literal(sql)})" for s, t, c, sql in rows)
    tables = len({(s, t) for s, t, _, _ in rows})
    return f"""-- platform-migration:{label}: {len(rows)} model defaults in {tables} relations made physical (generated by `manage.py ue_model_defaults_sql`).
-- A Django model that gives a column a default writes it on every INSERT, and the column had none, so a row written by any other writer failed (NOT NULL) or stored something else.
-- No Drizzle declaration names these relations: the model's default is the relation's own design, and the database takes it over unchanged. Every value below is the one the model already writes.
-- Rows that exist keep what they hold. A column that already has a default keeps it; a column that already carries a comment is refused, because the rollback finds what this migration set by its tag.
DO $defaults$
DECLARE
  r record;
  target regclass;
  column_number smallint;
  current_default text;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
{values}
    ) AS v(schema_name, table_name, column_name, default_sql)
    ORDER BY schema_name, table_name, column_name
  LOOP
    target := to_regclass(format('%I.%I', r.schema_name, r.table_name));
    IF target IS NULL THEN
      RAISE EXCEPTION 'platform model defaults fail-closed: %.% does not exist.', r.schema_name, r.table_name;
    END IF;
    SELECT a.attnum, pg_get_expr(d.adbin, d.adrelid) INTO column_number, current_default
      FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
     WHERE a.attrelid = target AND a.attname = r.column_name AND a.attnum > 0 AND NOT a.attisdropped;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'platform model defaults fail-closed: %.%.% does not exist.', r.schema_name, r.table_name, r.column_name;
    END IF;
    IF current_default IS NOT NULL THEN
      CONTINUE;
    END IF;
    IF col_description(target, column_number) IS NOT NULL THEN
      RAISE EXCEPTION 'platform model defaults fail-closed: %.%.% already carries a comment, so the rollback could not tell what this migration set.', r.schema_name, r.table_name, r.column_name;
    END IF;
    EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I SET DEFAULT %s', r.schema_name, r.table_name, r.column_name, r.default_sql);
    EXECUTE format('COMMENT ON COLUMN %I.%I.%I IS %L', r.schema_name, r.table_name, r.column_name, {tag});
  END LOOP;
END
$defaults$;
"""


def rollback(label):
    tag = literal(f"platform-migration:{label}:default")
    return f"""-- Rollback of platform-migration:{label}. It drops exactly the defaults that migration set (each carries its tag) and nothing that existed before it.
DO $rollback$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name, a.attname AS column_name
      FROM pg_description d
      JOIN pg_class c ON c.oid = d.objoid AND d.classoid = 'pg_class'::regclass
      JOIN pg_namespace n ON n.oid = c.relnamespace
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = d.objsubid
     WHERE d.objsubid > 0 AND d.description = {tag} AND NOT a.attisdropped
     ORDER BY 1, 2, 3
  LOOP
    EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I DROP DEFAULT', r.schema_name, r.table_name, r.column_name);
    EXECUTE format('COMMENT ON COLUMN %I.%I.%I IS NULL', r.schema_name, r.table_name, r.column_name);
  END LOOP;
END
$rollback$;
"""


class Command(BaseCommand):
    help = "Print the platform migration (or its rollback) that makes the models' defaults physical."

    def add_arguments(self, parser):
        parser.add_argument("--label", required=True, help="The migration label (3 to 61 characters of a-z, 0-9, _ and -).")
        parser.add_argument("--rollback", action="store_true", help="Print the rollback instead.")

    def handle(self, *args, **options):
        label = options["label"]
        if not (3 <= len(label) <= 61) or not all(ch.islower() or ch.isdigit() or ch in "_-" for ch in label):
            raise CommandError("--label must be 3 to 61 characters of a-z, 0-9, _ and -")
        rows = unbacked_defaults()
        if not rows:
            raise CommandError("no model default lacks a physical default: there is nothing to migrate")
        self.stdout.write(rollback(label) if options["rollback"] else forward(label, rows), ending="")
