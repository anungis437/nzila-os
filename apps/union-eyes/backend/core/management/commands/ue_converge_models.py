"""
Management command: bring the Django models, and the API they feed, in line with the physical PostgreSQL schema.

Usage:
    python manage.py ue_converge_models [--apply] [--apps a,b]

The platform migrations own the physical schema; the models are the ORM contract of every Django ViewSet, task and
command. Where the two disagree an ORM write fails (a NOT NULL column the model does not know) or a read returns less
than the table holds. This command edits the models' source so they describe the table, without widening the API:

  MODELS
  * a field is added for each physical column the model does not know (generated columns are written by PostgreSQL
    and are left alone);
  * a field that may send NULL (null=True) into a NOT NULL column stops doing so: ``null=True`` is removed, ``blank=True``
    is removed from non-text fields, and the column's default is carried over;
  * a field whose default differs from the column's constant default takes the column's (a Django write and a Drizzle
    write of the same row then agree), and a field with no default for a column that has one gets ``db_default``, which
    DRF does not read, so the serializer's required/optional contract does not move;
  * a response that projects a whole model with a bare ``.values()`` names its columns instead (core/api_projection.py),
    so completing the model does not widen it.

  SERIALIZERS (the API surface)
  * every reachable serializer that says ``fields = '__all__'`` is rewritten to the explicit list it produces today, so a
    column added to a model does not reach the API by itself. Nothing is added to those lists. Many reachable views are
    ``IsAuthenticated`` only, with no tenant scoping: a NOT NULL column the model did not know is what keeps their
    create path from writing, and exposing it would switch on cross-tenant writes. Exposing a column is a deliberate
    change to a view, made together with the scoping it needs.

Nothing in the database changes. Without --apply the command only reports. It is idempotent: a second run finds nothing
to do. Run ``ue_state_migrations`` afterwards to record the new model state.
"""
