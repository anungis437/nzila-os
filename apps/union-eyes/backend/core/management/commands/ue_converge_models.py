# Rendering: a small expression tree, so nested calls and long choice lists wrap instead of running off the line.


@dataclass
class Call:
    func: str
    args: list


@dataclass
class Kw:
    name: str
    value: object


@dataclass
class Seq:
    prefix: str
    items: list
    suffix: str


def inline(node):
    if isinstance(node, str):
        return node
    if isinstance(node, Kw):
        return f"{node.name}={inline(node.value)}"
    if isinstance(node, Seq):
        return node.prefix + ", ".join(inline(i) for i in node.items) + node.suffix
    return f"{node.func}({', '.join(inline(a) for a in node.args)})"


def render(node, indent):
    """The node as source, broken across lines when it does not fit; continuation lines are indented from ``indent``."""
    text = inline(node)
    if len(" " * indent + text) <= LINE_LIMIT:
        return text
    pad = " " * (indent + 4)
    if isinstance(node, Kw):
        return f"{node.name}={render(node.value, indent)}"
    if isinstance(node, Seq):
        lines, line = [], ""
        for item in node.items:
            piece = inline(item) + ","
            if line and len(pad + line + " " + piece) > LINE_LIMIT:
                lines.append(pad + line)
                line = piece
            else:
                line = f"{line} {piece}".strip()
        lines.append(pad + line)
        return node.prefix + "\n" + "\n".join(lines) + "\n" + " " * indent + node.suffix
    if isinstance(node, Call):
        body = "".join(f"{pad}{render(a, indent + 4)},\n" for a in node.args)
        return f"{node.func}(\n{body}{' ' * indent})"
    return text


def render_statement(attr, node):
    """A class-body field statement: one line when it fits, otherwise one argument per line."""
    one = f"    {attr} = {inline(node)}"
    if len(one) <= LINE_LIMIT or not (isinstance(node, Call) and node.args):
        return one
    body = "".join(f"        {render(a, 8)},\n" for a in node.args)
    return f"    {attr} = {node.func}(\n{body}    )"


