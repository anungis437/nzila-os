class SourceFile:
    def __init__(self, path):
        self.path = path
        with open(path, encoding="utf-8", newline="") as handle:
            self.text = handle.read()
        self.lines = self.text.split("\n")
        self.starts = [0]
        for line in self.lines:
            self.starts.append(self.starts[-1] + len(line) + 1)
        self.tree = ast.parse(self.text)
        self.edits = []
        self.imports_wanted = set()

    def offset(self, lineno, col_utf8):
        prefix = self.lines[lineno - 1].encode("utf-8")[:col_utf8].decode("utf-8")
        return self.starts[lineno - 1] + len(prefix)

    def class_node(self, name):
        for node in self.tree.body:
            if isinstance(node, ast.ClassDef) and node.name == name:
                return node
        return None

    def field_statement(self, cls, attr):
        for stmt in cls.body:
            if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name):
                if stmt.targets[0].id == attr and isinstance(stmt.value, ast.Call):
                    return stmt
        return None

    def insertion_line(self, cls):
        """The line after the last assignment that comes before Meta or any method."""
        last = None
        for stmt in cls.body:
            if isinstance(stmt, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                break
            if isinstance(stmt, (ast.Assign, ast.AnnAssign)):
                last = stmt
        if last is not None:
            return last.end_lineno
        first = cls.body[0]
        if isinstance(first, ast.Expr) and isinstance(getattr(first, "value", None), ast.Constant):
            return first.end_lineno
        return cls.lineno

    def insert_after(self, line, text):
        position = self.starts[line]
        self.edits.append((position, position, text + "\n"))

    def replace_node(self, node, text):
        start = self.offset(node.lineno, node.col_offset)
        end = self.offset(node.end_lineno, node.end_col_offset)
        self.edits.append((start, end, text))

    def segment(self, node):
        return ast.get_source_segment(self.text, node)

    def result(self):
        text = self.text
        for start, end, replacement in sorted(self.edits, key=lambda e: (e[0], e[1]), reverse=True):
            text = text[:start] + replacement + text[end:]
        return self.add_imports(text)

    IMPORTS = {
        "timezone": "from django.utils import timezone",
        "Decimal": "from decimal import Decimal",
        "uuid": "import uuid",
        "UnboundedDecimalField": "from core.fields import UnboundedDecimalField",
        "EnumArrayField": "from core.fields import EnumArrayField",
        "column_defaults": "from core import defaults as column_defaults",
        "ArrayField": "from django.contrib.postgres.fields import ArrayField",
        "SearchVectorField": "from django.contrib.postgres.search import SearchVectorField",
    }

    def add_imports(self, text):
        if not self.imports_wanted:
            return text
        tree = ast.parse(text)
        have, last_import = set(), 0
        for node in tree.body:
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                last_import = node.end_lineno
                for alias in node.names:
                    have.add(alias.asname or alias.name.split(".")[0])
        missing = [self.IMPORTS[n] for n in sorted(self.imports_wanted - have) if n in self.IMPORTS]
        if not missing:
            return text
        lines = text.split("\n")
        lines[last_import:last_import] = missing
        return "\n".join(lines)


def tightened_statement(src, stmt, drop_blank, default):
    """The field statement without ``null=True`` (and, for a non-text field, ``blank=True``), or None if it carries a comment."""
    call = stmt.value
    if "#" in src.segment(call):
        return None
    drop = {"null"} | ({"blank"} if drop_blank else set())
    present = {kw.arg for kw in call.keywords}
    parts = [src.segment(a) for a in call.args] + [src.segment(kw) for kw in call.keywords if kw.arg not in drop]
    if default is not None and "default" not in present:
        parts.append(f"default={default.expression}")
        src.imports_wanted |= default.imports
    attr = stmt.targets[0].id
    func = src.segment(call.func)
    one_line = f"{attr} = {func}({', '.join(parts)})"
    if len("    " + one_line) <= LINE_LIMIT:
        return one_line
    return f"{attr} = {func}(\n" + "".join(f"        {p},\n" for p in parts) + "    )"


def undefaulted_statement(src, stmt):
    """The field statement without ``default=``; None if it carries a comment."""
    call = stmt.value
    if "#" in src.segment(call):
        return None
    parts = [src.segment(a) for a in call.args] + [src.segment(kw) for kw in call.keywords if kw.arg != "default"]
    attr = stmt.targets[0].id
    func = src.segment(call.func)
    one_line = f"{attr} = {func}({', '.join(parts)})"
    if len("    " + one_line) <= LINE_LIMIT:
        return one_line
    return f"{attr} = {func}(\n" + "".join(f"        {p},\n" for p in parts) + "    )"


def defaulted_statement(src, stmt, keyword, expression):
    """The field statement with ``keyword`` (default or db_default) set to ``expression``; None if it carries a comment."""
    call = stmt.value
    if "#" in src.segment(call):
        return None
    parts = [src.segment(a) for a in call.args]
    replaced = False
    for kw in call.keywords:
        if kw.arg == keyword:
            parts.append(f"{keyword}={expression}")
            replaced = True
        else:
            parts.append(src.segment(kw))
    if not replaced:
        parts.append(f"{keyword}={expression}")
    attr = stmt.targets[0].id
    func = src.segment(call.func)
    one_line = f"{attr} = {func}({', '.join(parts)})"
    if len("    " + one_line) <= LINE_LIMIT:
        return one_line
    return f"{attr} = {func}(\n" + "".join(f"        {p},\n" for p in parts) + "    )"


def freeze_serializer(src, class_name, names):
    """Rewrite ``fields = '__all__'`` to the explicit list the serializer produces today. Returns a note, or None when done."""
    cls = src.class_node(class_name)
    meta = next((n for n in (cls.body if cls else []) if isinstance(n, ast.ClassDef) and n.name == "Meta"), None)
    stmt = None
    for node in meta.body if meta else []:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], "id", None) == "fields":
            stmt = node
    if stmt is None:
        return f"{class_name}: no Meta.fields assignment"
    value = stmt.value
    if isinstance(value, ast.Constant) and value.value == "__all__":
        src.replace_node(value, render(Seq("[", [repr(n) for n in names], "]"), 8))
        return None
    if isinstance(value, (ast.List, ast.Tuple)) and all(isinstance(e, ast.Constant) for e in value.elts):
        return None
    return f"{class_name}: Meta.fields is not a literal"


def mark_write_only(src, class_name, attrs):
    """Make the named fields write-only in the serializer's ``extra_kwargs``. Returns a note, or None when done."""
    cls = src.class_node(class_name)
    meta = next((n for n in (cls.body if cls else []) if isinstance(n, ast.ClassDef) and n.name == "Meta"), None)
    if meta is None:
        return f"{class_name}: no Meta"
    fields_stmt = extra = None
    for node in meta.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id == "fields":
                fields_stmt = node
            elif node.targets[0].id == "extra_kwargs":
                extra = node
    if extra is not None:
        try:
            declared = ast.literal_eval(extra.value)
        except ValueError:
            return f"{class_name}: extra_kwargs is not a literal; make {sorted(attrs)} write-only by hand"
        if all(declared.get(a, {}).get("write_only") for a in attrs):
            return None
        return f"{class_name}: extra_kwargs does not make {sorted(set(attrs) - set(declared))} write-only"
    if fields_stmt is None:
        return f"{class_name}: no Meta.fields assignment"
    entries = [f"{a!r}: {{'write_only': True}}" for a in sorted(attrs)]
    src.insert_after(fields_stmt.end_lineno, f"        extra_kwargs = {render(Seq('{', entries, '}'), 8)}")
    return None


