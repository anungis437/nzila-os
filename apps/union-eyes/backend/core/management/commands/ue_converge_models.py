def attribute_name(column, model):
    """The Python attribute for a column; ``db_column`` is needed when the column name cannot be one."""
    clash = (
        not column.isidentifier()
        or keyword.iskeyword(column)
        or column.startswith("_")
        or column.endswith("_")
        or "__" in column
        or column in RESERVED_ATTRIBUTES
        or hasattr(model, column)
    )
    if not clash:
        return column, None
    safe = re.sub(r"_+", "_", re.sub(r"\W", "_", column)).strip("_") or "column"
    if safe[0].isdigit():
        safe = "c_" + safe
    while hasattr(model, safe) or keyword.iskeyword(safe) or safe in RESERVED_ATTRIBUTES:
        safe += "_value"
    return safe, column


def choices_kw(values):
    # A list, not a tuple: a one-member enum would otherwise render as ('a'), which is a string.
    return Kw("choices", Seq("[(value, value) for value in [", [repr(v) for v in values], "]]"))


def enum_char(values):
    return Call("models.CharField", ["max_length=63", choices_kw(values)])


def scalar_field(type_text, labels, is_enum):
    """(call, kind, imports) for a non-array PostgreSQL type."""
    if is_enum:
        return enum_char(labels), "enum", set()
    t = type_text.strip()
    fam = family(t)
    if fam == "text":
        n = length_of(t)
        if n is not None and t.startswith(("character varying", "varchar", "character(", "char(")):
            return Call("models.CharField", [f"max_length={n}"]), "text", set()
        return Call("models.TextField", []), "text", set()
    if fam == "uuid":
        return Call("models.UUIDField", []), "uuid", set()
    if fam == "int":
        name = {"smallint": "SmallIntegerField", "bigint": "BigIntegerField"}.get(t, "IntegerField")
        return Call(f"models.{name}", []), "int", set()
    if fam == "numeric":
        p = precision_of(t)
        if p:
            return Call("models.DecimalField", [f"max_digits={p[0]}", f"decimal_places={p[1]}"]), "numeric", set()
        return Call("UnboundedDecimalField", []), "numeric", {"UnboundedDecimalField"}
    simple = {
        "float": "FloatField",
        "bool": "BooleanField",
        "timestamptz": "DateTimeField",
        "timestamp": "DateTimeField",
        "date": "DateField",
        "time": "TimeField",
        "json": "JSONField",
        "inet": "GenericIPAddressField",
        "bytea": "BinaryField",
        "interval": "DurationField",
    }
    if fam in simple:
        return Call(f"models.{simple[fam]}", []), fam, set()
    if t == "tsvector":
        return Call("SearchVectorField", []), "tsvector", {"SearchVectorField"}
    raise Unmapped(type_text)


def field_call(column, catalog):
    """(call, kind, imports) for a physical column."""
    type_text = column["type"]
    if type_text.endswith("[]"):
        if type_text.endswith("[][]"):
            raise Unmapped(type_text)
        if column["elem_enum"]:
            labels = catalog.enums[column["elem_oid"]]
            call = Call("EnumArrayField", [enum_char(labels), f"enum_type={column['elem_name']!r}"])
            return call, "array", {"EnumArrayField"}
        inner, _, needs = scalar_field(type_text[:-2], None, False)
        return Call("ArrayField", [inner]), "array", needs | {"ArrayField"}
    labels = catalog.enums[column["typoid"]] if column["enum"] else None
    return scalar_field(type_text, labels, column["enum"])


@dataclass
class Default:
    expression: str
    imports: set = field(default_factory=set)
    helper: tuple = None  # (function name, return expression)


def helper_default(table, column, value):
    name = re.sub(r"\W", "_", f"{table}__{column}")
    return Default(f"column_defaults.{name}", {"column_defaults"}, (name, repr(value)))


def python_default(expression, kind, table, column):
    """The Python ``default=`` for a column default, or None when the column has none. Raises when it cannot say it."""
    if expression is None:
        return None
    e = expression.strip()
    if e in ("now()", "CURRENT_TIMESTAMP", "statement_timestamp()", "clock_timestamp()", "transaction_timestamp()") or e.startswith("timezone("):
        return Default("timezone.now", {"timezone"})
    if e == "gen_random_uuid()":
        return Default("uuid.uuid4", {"uuid"})
    if e in ("false", "true"):
        return Default(e.capitalize())
    m = NUMBER.match(e)
    if m:
        number = m.group(1)
        if kind == "numeric":
            return Default(f"Decimal('{number}')", {"Decimal"})
        if kind == "float":
            return Default(repr(float(number)))
        if kind == "int" and "." not in number:
            return Default(str(int(number)))
        raise UnexpressibleDefault(expression)
    m = QUOTED.match(e)
    if m:
        value, cast, is_array = m.group(1).replace("''", "'"), m.group(2), m.group(3)
        if is_array:
            try:
                items = parse_pg_array(value)
            except ValueError as error:
                raise UnexpressibleDefault(expression) from error
            return Default("list") if not items else helper_default(table, column, items)
        if cast in ("jsonb", "json"):
            try:
                parsed = json.loads(value)
            except ValueError as error:
                raise UnexpressibleDefault(expression) from error
            if parsed == {}:
                return Default("dict")
            if parsed == []:
                return Default("list")
            return helper_default(table, column, parsed)
        if cast == "numeric":
            return Default(f"Decimal('{value}')", {"Decimal"})
        return Default(repr(value))
    m = ARRAY_LITERAL.match(e)
    if m:
        elements = split_arguments(m.group(1))
        if not elements:
            return Default("list")
        values = []
        for element in elements:
            q = QUOTED.match(element)
            if not q:
                raise UnexpressibleDefault(expression)
            values.append(q.group(1).replace("''", "'"))
        return helper_default(table, column, values)
    raise UnexpressibleDefault(expression)


def with_arguments(call, extra):
    return Call(call.func, list(call.args) + extra)


