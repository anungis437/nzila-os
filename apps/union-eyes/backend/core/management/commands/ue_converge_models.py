class Command(BaseCommand):
    help = "Edit the Django models and serializers so the models describe the physical schema and the API stays the same."

    def add_arguments(self, parser):
        parser.add_argument("--apply", action="store_true", help="Write the edited files.")
        parser.add_argument("--apps", default="", help="Comma-separated app labels to converge.")
        parser.add_argument(
            "--declared-not-null",
            default="",
            help="JSON register of NOT_NULL_ABSENT findings (scripts/runtime/orm-physical-parity.ts --kinds=NOT_NULL_ABSENT --write): "
            "the models require those columns too, so the platform can make them NOT NULL.",
        )
        parser.add_argument("--keep-nullable", default="", help="Comma-separated table.column that stay nullable on purpose.")
        parser.add_argument(
            "--drop-defaults",
            default="",
            help="JSON list of table.column whose model default is removed: the platform declares none, so a Django INSERT must not write "
            "a value no other writer writes.",
        )

    def handle(self, *args, **options):
        labels = {a for a in options["apps"].split(",") if a}
        with connection.cursor() as cursor:
            catalog = Catalog(cursor)

        drop_defaults = set()
        if options["drop_defaults"]:
            with open(options["drop_defaults"], encoding="utf-8") as handle:
                drop_defaults = set(json.load(handle))
        declared_required = set()
        if options["declared_not_null"]:
            kept = {k for k in options["keep_nullable"].split(",") if k}
            with open(options["declared_not_null"], encoding="utf-8") as handle:
                for finding in json.load(handle)["findings"]:
                    if finding["kind"] == "NOT_NULL_ABSENT" and finding.get("column") and f"{finding['table']}.{finding['column']}" not in kept:
                        declared_required.add((finding["table"].split(".")[-1], finding["column"]))

        live = exposure.live_serializers()

        files = {}

        def source(path):
            return files.get(path) or files.setdefault(path, SourceFile(path))

        added = defaultdict(int)
        tightened, unmapped, manual, defaulted, dropped = [], [], [], [], []
        helpers = {}
        new_attrs = defaultdict(list)

        for model in apps.get_models():
            meta = model._meta
            if meta.proxy or meta.abstract or not meta.managed or meta.app_label in CONTRIB_APPS:
                continue
            if labels and meta.app_label not in labels:
                continue
            physical = catalog.columns.get(split_table(meta.db_table))
            if physical is None:
                continue
            src = source(inspect.getsourcefile(model))
            cls = src.class_node(model.__name__)
            if cls is None:
                manual.append((meta.db_table, f"class {model.__name__} not found in {src.path}"))
                continue

            known = {f.column for f in meta.local_concrete_fields}
            new_lines = []
            for name, column in physical.items():
                if name in known or column["generated"]:
                    continue
                attr, db_column = attribute_name(name, model)
                try:
                    call, kind, needs = field_call(column, catalog)
                    default = python_default(column["default"], kind, meta.db_table, name)
                except Unmapped as error:
                    unmapped.append((meta.db_table, name, str(error)))
                    continue
                except UnexpressibleDefault as error:
                    raise CommandError(f"{meta.db_table}.{name}: cannot express the default {error}") from error
                extra = []
                if db_column:
                    extra.append(f"db_column={db_column!r}")
                if default:
                    extra.append(f"default={default.expression}")
                    needs = needs | default.imports
                    if default.helper:
                        helpers[default.helper[0]] = default.helper[1]
                if not column["notnull"]:
                    extra += ["null=True", "blank=True"]
                new_lines.append(render_statement(attr, with_arguments(call, extra)))
                src.imports_wanted |= needs
                added[meta.app_label] += 1
                new_attrs[meta.db_table].append((attr, name))
            if new_lines:
                src.insert_after(src.insertion_line(cls), "\n".join(new_lines))

            for fld in meta.local_concrete_fields:
                column = physical.get(fld.column)
                if column is None or column["identity"] or column["generated"]:
                    continue
                if not (column["notnull"] or (split_table(meta.db_table)[1], fld.column) in declared_required):
                    continue
                if not model_permits_null(fld):
                    continue
                stmt = src.field_statement(cls, fld.name)
                if stmt is None:
                    manual.append((meta.db_table, f"{fld.name}: the field is not a plain assignment in the class body"))
                    continue
                if fld.remote_field is not None and fld.remote_field.on_delete is models.SET_NULL:
                    manual.append((meta.db_table, f"{fld.name}: SET_NULL on a foreign key over a NOT NULL column"))
                    continue
                try:
                    kind = "array" if column["type"].endswith("[]") else field_call(column, catalog)[1]
                    default = python_default(column["default"], kind, meta.db_table, fld.column)
                except Unmapped as error:
                    unmapped.append((meta.db_table, fld.column, str(error)))
                    continue
                except UnexpressibleDefault as error:
                    raise CommandError(f"{meta.db_table}.{fld.column}: cannot express the default {error}") from error
                text = tightened_statement(src, stmt, kind not in ("text", "enum"), default)
                if text is None:
                    manual.append((meta.db_table, f"{fld.name}: the statement carries a comment"))
                    continue
                if default and default.helper:
                    helpers[default.helper[0]] = default.helper[1]
                src.replace_node(stmt, text)
                tightened.append((meta.db_table, fld.column))

            for fld in meta.local_concrete_fields:
                column = physical.get(fld.column)
                if column is None or fld.primary_key or is_auto(fld) or column["identity"] or column["generated"]:
                    continue
                if (meta.db_table, fld.column) in tightened or getattr(fld, "auto_now", False) or getattr(fld, "auto_now_add", False):
                    continue
                is_constant, physical_value = constant_default(column["default"])
                if not is_constant:
                    continue
                written = model_default(fld)
                if written is COMPUTED or (written is not NOT_PROVIDED and defaults_agree(written, physical_value)):
                    continue
                stmt = src.field_statement(cls, fld.name)
                if stmt is None:
                    manual.append((meta.db_table, f"{fld.name}: the field is not a plain assignment in the class body"))
                    continue
                try:
                    kind = "array" if column["type"].endswith("[]") else field_call(column, catalog)[1]
                    default = python_default(column["default"], kind, meta.db_table, fld.column)
                except Unmapped as error:
                    unmapped.append((meta.db_table, fld.column, str(error)))
                    continue
                except UnexpressibleDefault as error:
                    raise CommandError(f"{meta.db_table}.{fld.column}: cannot express the default {error}") from error
                # A field that already names a default keeps naming one. A field that names none gets the database's own:
                # db_default leaves the serializer's required/optional contract as it is (DRF reads default, not db_default).
                keyword = "default" if written is not NOT_PROVIDED else "db_default"
                if keyword == "db_default" and default.helper:
                    raise CommandError(f"{meta.db_table}.{fld.column}: a db_default cannot be a generated callable")
                text = defaulted_statement(src, stmt, keyword, default.expression)
                if text is None:
                    manual.append((meta.db_table, f"{fld.name}: the statement carries a comment"))
                    continue
                if default.helper:
                    helpers[default.helper[0]] = default.helper[1]
                src.imports_wanted |= default.imports
                src.replace_node(stmt, text)
                defaulted.append((meta.db_table, fld.column, keyword))

            for fld in meta.local_concrete_fields:
                key = f"{meta.db_table}.{fld.column}"
                if key not in drop_defaults or fld.default is NOT_PROVIDED:
                    continue
                if (meta.db_table, fld.column) in tightened or any(d[:2] == (meta.db_table, fld.column) for d in defaulted):
                    manual.append((meta.db_table, f"{fld.name}: already edited in this run; drop its default in a separate run"))
                    continue
                stmt = src.field_statement(cls, fld.name)
                if stmt is None:
                    manual.append((meta.db_table, f"{fld.name}: the field is not a plain assignment in the class body"))
                    continue
                text = undefaulted_statement(src, stmt)
                if text is None:
                    manual.append((meta.db_table, f"{fld.name}: the statement carries a comment"))
                    continue
                src.replace_node(stmt, text)
                dropped.append((meta.db_table, fld.column))
        frozen, serializer_notes, preexisting_sensitive = 0, [], []
        for serializer, model in live.items():
            if labels and model._meta.app_label not in labels:
                continue
            names = list(serializer().fields)
            for name in names:
                if exposure.SENSITIVE_COLUMN.search(name):
                    preexisting_sensitive.append((model._meta.db_table, serializer.__name__, name))
            if getattr(serializer.Meta, "fields", None) != "__all__":
                continue
            note = freeze_serializer(source(inspect.getsourcefile(serializer)), serializer.__name__, names)
            if note:
                serializer_notes.append(note)
            else:
                frozen += 1

        # A credential is never returned by any serializer, routed or not: un-containing a view must not publish it.
        write_only_marked = 0
        for serializer, model in exposure.model_serializers().items():
            meta = model._meta
            if labels and meta.app_label not in labels:
                continue
            if getattr(serializer.Meta, "fields", None) != "__all__":
                continue
            attrs = {f.name for f in meta.local_concrete_fields if exposure.SENSITIVE_COLUMN.search(f.column)}
            attrs |= {attr for attr, column in new_attrs.get(meta.db_table, []) if exposure.SENSITIVE_COLUMN.search(column)}
            if not attrs:
                continue
            note = mark_write_only(source(inspect.getsourcefile(serializer)), serializer.__name__, attrs)
            if note:
                serializer_notes.append(note)
            else:
                write_only_marked += 1

        report = {
            "files": len(files),
            "columns_added": dict(added),
            "columns_added_total": sum(added.values()),
            "fields_tightened": len(tightened),
            "fields_defaulted": defaulted,
            "defaults_dropped": dropped,
            "defaults_requested_but_absent": sorted(drop_defaults - {f"{t}.{c}" for t, c in dropped}),
            "serializers_frozen": frozen,
            "serializers_with_write_only_credentials": write_only_marked,
            "helper_defaults": sorted(helpers),
            "preexisting_sensitive_fields_on_live_serializers": preexisting_sensitive,
            "unmapped_types": unmapped,
            "serializer_notes": serializer_notes,
            "manual": manual,
        }
        self.stdout.write(json.dumps(report, indent=1, default=str))
        if not options["apply"]:
            return

        for path, src in files.items():
            if not src.edits:
                continue
            result = src.result()
            try:
                compile(result, path, "exec")
            except SyntaxError as error:
                raise CommandError(f"{path}: the edited source does not compile: {error}") from error
            with open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write(result)

        self.write_defaults(helpers)
        self.stdout.write("model, serializer and defaults files written")

    def write_defaults(self, helpers):
        existing = DEFAULTS_FILE.read_text(encoding="utf-8") if DEFAULTS_FILE.exists() else DEFAULTS_HEADER
        have = {n.name for n in ast.parse(existing).body if isinstance(n, ast.FunctionDef)}
        additions = "".join(
            f"\n\ndef {name}():\n    return {expression}\n" for name, expression in sorted(helpers.items()) if name not in have
        )
        if additions or not DEFAULTS_FILE.exists():
            DEFAULTS_FILE.write_text(existing.rstrip("\n") + "\n" + additions, encoding="utf-8", newline="\n")
