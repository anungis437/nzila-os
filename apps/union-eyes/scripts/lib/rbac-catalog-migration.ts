/**
 * Renders platform migration 0076 (enhanced RBAC catalog and integrity, UE-CONV-H-010) from the code catalog in lib/auth/roles.ts, so the database and the code
 * cannot describe different roles: the seed is generated, and lib/auth/__tests__/role-catalog-consistency.test.ts regenerates it and compares it with the
 * committed file. Nothing here touches a database.
 *
 *   npx tsx scripts/generate-rbac-catalog-migration.ts > db/migrations-platform/0076_enhanced_rbac_catalog.sql
 *   npx tsx scripts/generate-rbac-catalog-migration.ts --rollback > db/migrations-platform/0076_enhanced_rbac_catalog.rollback.sql
 */
import { getRoleLevel, Permission, ROLE_PERMISSIONS, TENANT_LOCAL_ROLES, UserRole } from '../../lib/auth/roles'

export const MIGRATION_LABEL = 'enhanced_rbac_catalog'

/** What each organization role is called. A role added to TENANT_LOCAL_ROLES without a name stops the generator. */
const ROLE_NAMES: Readonly<Record<string, string>> = {
  admin: 'Organization Administrator',
  president: 'Union President',
  vice_president: 'Vice President',
  secretary_treasurer: 'Secretary-Treasurer',
  chief_steward: 'Chief Steward',
  officer: 'Union Officer',
  clerk: 'Admin Clerk',
  steward: 'Union Steward',
  bargaining_committee: 'Bargaining Committee Member',
  health_safety_rep: 'Health & Safety Representative',
  member: 'Union Member',
}

export interface SystemRole {
  code: string
  name: string
  level: number
  permissions: string[]
}

/** The organization roles, highest level first, each with its level and permissions exactly as the code catalog states them. */
export function systemRoles(): SystemRole[] {
  return [...TENANT_LOCAL_ROLES]
    .map((role): SystemRole => {
      const name = ROLE_NAMES[role]
      if (!name) throw new Error(`role ${role} is in TENANT_LOCAL_ROLES but has no display name in scripts/lib/rbac-catalog-migration.ts`)
      const permissions: Permission[] = ROLE_PERMISSIONS[role as UserRole] ?? []
      return { code: role, name, level: getRoleLevel(role as UserRole), permissions: [...new Set<string>(permissions)].sort() }
    })
    .sort((a, b) => b.level - a.level || a.code.localeCompare(b.code))
}

const lit = (value: string): string => `'${value.replace(/'/g, "''")}'`
const SEP = '\n--> statement-breakpoint\n'
// A statement ends with a semicolon so the file also runs as one script (psql, a client.query of the whole file); the runner splits on the breakpoint marker.
const terminated = (parts: string[]): string => `${parts.map((part) => (part.startsWith('--') ? part : `${part};`)).join(SEP)}\n`
const TAG = `platform-migration:${MIGRATION_LABEL}`

const FUNCTIONS = [
  'public.rbac_audit_log_append_only()',
  'public.rbac_member_organization_guard()',
]
const TRIGGERS: Array<{ name: string; table: string }> = [
  { name: 'rbac_audit_log_append_only', table: 'public.rbac_audit_log' },
  { name: 'rbac_audit_log_no_truncate', table: 'public.rbac_audit_log' },
  { name: 'member_roles_member_organization', table: 'public.member_roles' },
  { name: 'permission_exceptions_member_organization', table: 'public.permission_exceptions' },
]

export function renderCatalogMigration(): string {
  const roles = systemRoles()
  const codes = roles.map((r) => lit(r.code)).join(', ')
  const values = roles
    .map((r) => `  (${lit(r.code)}, ${lit(r.name)}, ${r.level}, ${lit(JSON.stringify(r.permissions))}::jsonb, true, true)`)
    .join(',\n')
  const parts = [
    `-- ${TAG}: integrity for the enhanced RBAC relations created by 0075, and the ${roles.length} organization roles of the code catalog (generated by scripts/generate-rbac-catalog-migration.ts).
-- * rbac_audit_log is append-only: a row is never deleted or truncated, and the only change allowed is recording a review, once.
-- * member_roles and permission_exceptions refuse a member who does not belong to the row's organization (a tenant-owned role row must never name another organization's member),
--   and member_roles refuses a role that is not an active role of the catalog.
-- * role_definitions is seeded with the roles an organization can hold (TENANT_LOCAL_ROLES in lib/auth/roles.ts), with the level getRoleLevel() gives and the permissions
--   ROLE_PERMISSIONS gives. The Nzila platform-operations and CLC/federation/national roles are deliberately not seeded: a role row in tenant data must not be able to carry a
--   level that opens another organization or the platform. A custom role that already uses a seeded code stops the migration; nothing is overwritten.`,
    `CREATE OR REPLACE FUNCTION public.rbac_audit_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP IN ('DELETE', 'TRUNCATE') THEN
    RAISE EXCEPTION 'rbac_audit_log is append-only: rows are never deleted' USING ERRCODE = 'restrict_violation';
  END IF;
  IF OLD.reviewed_at IS NOT NULL THEN
    RAISE EXCEPTION 'rbac_audit_log is append-only: a recorded review is never changed' USING ERRCODE = 'restrict_violation';
  END IF;
  IF (to_jsonb(OLD) - 'reviewed_at' - 'reviewed_by' - 'review_notes') IS DISTINCT FROM (to_jsonb(NEW) - 'reviewed_at' - 'reviewed_by' - 'review_notes') THEN
    RAISE EXCEPTION 'rbac_audit_log is append-only: only the review columns may change' USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END
$fn$`,
    `DROP TRIGGER IF EXISTS rbac_audit_log_append_only ON public.rbac_audit_log`,
    `CREATE TRIGGER rbac_audit_log_append_only BEFORE UPDATE OR DELETE ON public.rbac_audit_log FOR EACH ROW EXECUTE FUNCTION public.rbac_audit_log_append_only()`,
    `DROP TRIGGER IF EXISTS rbac_audit_log_no_truncate ON public.rbac_audit_log`,
    `CREATE TRIGGER rbac_audit_log_no_truncate BEFORE TRUNCATE ON public.rbac_audit_log FOR EACH STATEMENT EXECUTE FUNCTION public.rbac_audit_log_append_only()`,
    `CREATE OR REPLACE FUNCTION public.rbac_member_organization_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.organization_members m WHERE m.id = NEW.member_id AND m.organization_id = NEW.organization_id) THEN
    RAISE EXCEPTION 'member % does not belong to organization %', NEW.member_id, NEW.organization_id USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF TG_TABLE_NAME = 'member_roles' THEN
    IF NEW.acting_for_member_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.organization_members m WHERE m.id = NEW.acting_for_member_id AND m.organization_id = NEW.organization_id
    ) THEN
      RAISE EXCEPTION 'acting-for member % does not belong to organization %', NEW.acting_for_member_id, NEW.organization_id USING ERRCODE = 'foreign_key_violation';
    END IF;
    IF (TG_OP = 'INSERT' OR NEW.role_code IS DISTINCT FROM OLD.role_code)
       AND NOT EXISTS (SELECT 1 FROM public.role_definitions d WHERE d.role_code = NEW.role_code AND d.is_active) THEN
      RAISE EXCEPTION 'role % is not an active role', NEW.role_code USING ERRCODE = 'foreign_key_violation';
    END IF;
  END IF;
  RETURN NEW;
END
$fn$`,
    `DROP TRIGGER IF EXISTS member_roles_member_organization ON public.member_roles`,
    `CREATE TRIGGER member_roles_member_organization BEFORE INSERT OR UPDATE OF member_id, organization_id, acting_for_member_id, role_code ON public.member_roles FOR EACH ROW EXECUTE FUNCTION public.rbac_member_organization_guard()`,
    `DROP TRIGGER IF EXISTS permission_exceptions_member_organization ON public.permission_exceptions`,
    `CREATE TRIGGER permission_exceptions_member_organization BEFORE INSERT OR UPDATE OF member_id, organization_id ON public.permission_exceptions FOR EACH ROW EXECUTE FUNCTION public.rbac_member_organization_guard()`,
    `DO $seed$
BEGIN
  IF to_regclass('public.role_definitions') IS NULL THEN
    RAISE EXCEPTION 'platform ${MIGRATION_LABEL} fail-closed: public.role_definitions does not exist (platform 0075 not applied).';
  END IF;
  IF EXISTS (SELECT 1 FROM public.role_definitions WHERE role_code IN (${codes}) AND NOT is_system_role) THEN
    RAISE EXCEPTION 'platform ${MIGRATION_LABEL} fail-closed: a custom role already uses a system role code (%).',
      (SELECT string_agg(role_code, ', ' ORDER BY role_code) FROM public.role_definitions WHERE role_code IN (${codes}) AND NOT is_system_role);
  END IF;
END
$seed$`,
    `INSERT INTO public.role_definitions (role_code, role_name, role_level, permissions, is_system_role, is_active) VALUES
${values}
ON CONFLICT (role_code) DO UPDATE
   SET role_name = EXCLUDED.role_name, role_level = EXCLUDED.role_level, permissions = EXCLUDED.permissions, updated_at = now()
 WHERE public.role_definitions.is_system_role`,
  ]
  return terminated(parts)
}

export function renderCatalogRollback(): string {
  const codes = systemRoles().map((r) => lit(r.code)).join(', ')
  const parts = [
    `-- Rollback of ${TAG}. It refuses while a member still holds a seeded system role, then removes the seeded roles and the triggers and functions that migration created.`,
    `DO $rollback$
BEGIN
  IF to_regclass('public.member_roles') IS NOT NULL AND EXISTS (SELECT 1 FROM public.member_roles WHERE role_code IN (${codes})) THEN
    RAISE EXCEPTION 'platform ${MIGRATION_LABEL} rollback fail-closed: member_roles still holds a seeded system role; end those assignments first.';
  END IF;
  IF to_regclass('public.role_definitions') IS NOT NULL THEN
    DELETE FROM public.role_definitions WHERE is_system_role AND role_code IN (${codes});
  END IF;
END
$rollback$`,
    ...TRIGGERS.map((t) => `DO $rollback$ BEGIN IF to_regclass(${lit(t.table)}) IS NOT NULL THEN DROP TRIGGER IF EXISTS ${t.name} ON ${t.table}; END IF; END $rollback$`),
    ...FUNCTIONS.map((f) => `DROP FUNCTION IF EXISTS ${f}`),
  ]
  return terminated(parts)
}
