/**
 * Console primary navigation — typed config.
 *
 * This file is the single source of truth for the dashboard sidebar.
 * Extracted from `app/(dashboard)/layout.tsx` so:
 *   - structure is reviewable in isolation
 *   - it can be filtered by role / feature flag / search at the call site
 *   - tests can assert routing invariants (every href maps to a real page)
 *
 * Conventions:
 *   - `icon` is a string key into `iconMap` in `components/sidebar-nav.tsx`
 *   - `requiredRole` (optional) is enforced by the layout before render
 *   - `featureFlag` (optional) is read from env or remote flag service
 *   - Groups render top-to-bottom; `defaultOpen` opens that group on first paint
 */
import type { NavGroup } from '@/components/sidebar-nav'

export interface NavItemConfig {
  name: string
  href: string
  icon: string
  description?: string
  badge?: string
  /** Roles that may see this item. Empty/undefined → visible to all authenticated users. */
  requiredRoles?: string[]
  /** If set, item is hidden unless the named flag is enabled. */
  featureFlag?: string
}

export interface NavGroupConfig extends Omit<NavGroup, 'items'> {
  label: string
  defaultOpen?: boolean
  items: NavItemConfig[]
}

/** External app launcher entries (not part of dashboard routing). */
export interface AppLinkConfig {
  name: string
  /** Resolved at module-load from `process.env.NEXT_PUBLIC_*` */
  href: string | undefined
  badge: string
}

