/**
 * Filter nav groups against a set of role grants and enabled feature flags.
 * Empty groups (after filtering) are dropped so the layout never renders an
 * empty section header.
 *
 * Both `roles` and `enabledFlags` default to "allow everything" — pass them
 * explicitly when role-aware filtering is wired up.
 */
export function filterNav(
  groups: NavGroupConfig[],
  opts: { roles?: Set<string>; enabledFlags?: Set<string> } = {},
): NavGroupConfig[] {
  const { roles, enabledFlags } = opts
  return groups
    .map(group => ({
      ...group,
      items: group.items.filter(item => {
        if (item.featureFlag && enabledFlags && !enabledFlags.has(item.featureFlag)) return false
        if (item.requiredRoles && roles) {
          return item.requiredRoles.some(r => roles.has(r))
        }
        return true
      }),
    }))
    .filter(group => group.items.length > 0)
}
