/**
 * Generates docs/union-eyes/workaid/CHANGED_SOURCE_INVENTORY.md: every path the
 * branch adds or changes relative to the verified base, grouped by area, with a
 * hard check that nothing lies outside the two preparation prefixes.
 *   node scripts/inventory.ts
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { preflight, safeWrite } from './guard.ts';

preflight();
const BASE = '38a824918cf2e7d7cfb7fcb0e796cbde45433be8';
const repoRoot = resolve(import.meta.dirname, '..', '..', '..');
const git = (...a: string[]) => execFileSync('git', ['--no-optional-locks', ...a], { cwd: repoRoot, encoding: 'utf8' }).split(/\r?\n/).filter(Boolean);

const tracked = git('diff', '--name-status', BASE).map((l) => {
  const [status, ...rest] = l.split('\t');
  return { path: rest.join('\t'), status: status === 'A' ? 'added' : status === 'M' ? 'modified' : status === 'D' ? 'deleted' : status! };
});
const untracked = git('ls-files', '--others', '--exclude-standard').map((path) => ({ path, status: 'added' }));
const all = [...new Map([...tracked, ...untracked].map((e) => [e.path, e])).values()].sort((a, b) => a.path.localeCompare(b.path));

const area = (p: string) =>
  p.startsWith('tooling/workaid-prep/src/platform-repro/') ? 'Harness — platform reproductions (routed to Codex)'
  : p.startsWith('tooling/workaid-prep/src/') ? 'Harness — domain contracts'
  : p.startsWith('tooling/workaid-prep/test/') ? 'Harness — synthetic tests'
  : p.startsWith('tooling/workaid-prep/scripts/') ? 'Harness — scripts (runner, parsers, builders)'
  : p.startsWith('tooling/workaid-prep/') ? 'Harness — config and README'
  : p.startsWith('docs/union-eyes/workaid/baseline-pack-v0.1/') ? 'Input — WorkAid preparation pack v0.1 (verbatim)'
  : p.startsWith('docs/union-eyes/workaid/grok-redteam-01/') ? 'Input — Grok R3–R6 deliverables (verbatim)'
  : p.startsWith('docs/union-eyes/workaid/data/') ? 'Docs — generated data'
  : p.startsWith('docs/union-eyes/workaid/evidence/') ? 'Docs — evidence'
  : p.startsWith('docs/union-eyes/workaid/') ? 'Docs — deliverables'
  : 'OUTSIDE PREPARATION AREA';

const lines = (p: string) => {
  if (p.endsWith('CHANGED_SOURCE_INVENTORY.md') || p.endsWith('evidence/harness-manifest.json')) return 0; // self-referential; keeps the generator idempotent
  try {
    return readFileSync(join(repoRoot, p), 'utf8').split('\n').length;
  } catch {
    return 0;
  }
};
const groups = new Map<string, typeof all>();
for (const e of all) groups.set(area(e.path), [...(groups.get(area(e.path)) ?? []), e]);
const outside = groups.get('OUTSIDE PREPARATION AREA') ?? [];

const md: string[] = [];
md.push('# Changed-source inventory');
md.push('');
md.push(`> Generated by \`tooling/workaid-prep/scripts/inventory.ts\`. Base: \`${BASE}\` (verified \`origin/main\`). Branch \`agents/workaid-prep-20261023\`.`);
md.push('');
md.push(`**${all.length} paths added or changed; ${outside.length} outside the two preparation prefixes.** Modified or deleted existing files: ${all.filter((e) => e.status !== 'added').length}.`);
md.push('');
md.push('| Area | Files | Lines |');
md.push('|---|---:|---:|');
for (const [a, es] of [...groups.entries()].sort()) md.push(`| ${a} | ${es.length} | ${es.reduce((n, e) => n + lines(e.path), 0)} |`);
md.push('');
md.push('## Files');
md.push('');
for (const [a, es] of [...groups.entries()].sort()) {
  md.push(`### ${a}`);
  md.push('');
  for (const e of es) md.push(`- \`${e.path}\` (${e.status})`);
  md.push('');
}
md.push('## Not touched');
md.push('');
md.push('`package.json`, `pnpm-lock.yaml`, `pnpm-workspace.yaml`, `turbo.json`, `vitest.config.ts`, `.github/**`, `apps/**`, `packages/**`, `migrations/**`, `infrastructure/**`, `governance/**`, `tooling/` other than `workaid-prep`, the staging database, migration journal and release manifests. Asserted by `test/isolation.test.ts`.');
md.push('');
safeWrite(join(repoRoot, 'docs', 'union-eyes', 'workaid', 'CHANGED_SOURCE_INVENTORY.md'), md.join('\n'));
console.log(JSON.stringify({ paths: all.length, outside: outside.length }));
if (outside.length > 0) process.exitCode = 1;
