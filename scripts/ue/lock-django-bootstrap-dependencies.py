"""Build a hash-pinned pip lock from two independent repository-driven resolutions."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name
from pip._vendor.packaging.version import Version

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "apps" / "union-eyes" / "backend"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def normalize(report):
    records = []
    for entry in report["install"]:
        metadata = entry["metadata"]
        name = canonicalize_name(metadata["name"])
        artifact = entry["download_info"]
        artifact_hash = artifact["archive_info"]["hashes"]["sha256"]
        assert re.fullmatch(r"[a-f0-9]{64}", artifact_hash)
        assert artifact["url"].startswith("https://files.pythonhosted.org/")
        records.append({
            "DISTRIBUTION": name, "VERSION": metadata["version"],
            "DIRECT": entry["requested"],
            "ARTIFACT_URL": artifact["url"], "ARTIFACT_SHA256": artifact_hash,
            "ARTIFACT_FILENAME": artifact["url"].split("/")[-1],
            "REQUIRES_DIST": sorted(metadata.get("requires_dist", [])),
            "REQUIRES_PYTHON": metadata.get("requires_python"),
        })
    records.sort(key=lambda row: row["DISTRIBUTION"])
    assert len({row["DISTRIBUTION"] for row in records}) == len(records)
    return records


def lock_text(records):
    return (
        "# Generated by scripts/ue/lock-django-bootstrap-dependencies.py.\n"
        "# Candidate target: CPython 3.11.14, Linux x86_64, manylinux2014, cp311.\n"
        "# One exact artifact per distribution; not portable to other targets.\n"
        "# W1 runtime/app/marker decisions remain blocked; this is not a deployment change.\n"
        + "\n".join(
            f"{row['DISTRIBUTION']}=={row['VERSION']} "
            f"--hash=sha256:{row['ARTIFACT_SHA256']}" for row in records
        ) + "\n"
    )


def build(first, second):
    run1, run2 = normalize(first), normalize(second)
    assert run1 == run2, "NONDETERMINISTIC_RESOLVER_OUTPUT"
    text = (BACKEND / "requirements.txt").read_text(encoding="utf-8")
    declared = []
    locked = {row["DISTRIBUTION"]: row for row in run1}
    for index, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        requirement = Requirement(line)
        name = canonicalize_name(requirement.name)
        assert name in locked, f"Unresolved direct requirement: {name}"
        assert Version(locked[name]["VERSION"]) in requirement.specifier
        declared.append({
            "DISTRIBUTION": name, "DECLARED_CONSTRAINT": str(requirement.specifier),
            "EXTRAS": sorted(requirement.extras), "LINE": index,
            "LOCKED_VERSION": locked[name]["VERSION"],
        })
    assert len(set(row["DISTRIBUTION"] for row in declared)) == len(declared)
    assert {row["DISTRIBUTION"] for row in declared} == {
        row["DISTRIBUTION"] for row in run1 if row["DIRECT"]
    }
    target = {
        "implementation_name": "cpython", "implementation_version": "3.11.14",
        "os_name": "posix", "platform_machine": "x86_64",
        "platform_python_implementation": "CPython", "platform_release": "",
        "platform_system": "Linux", "platform_version": "",
        "python_full_version": "3.11.14", "python_version": "3.11",
        "sys_platform": "linux",
    }
    extras = {row["DISTRIBUTION"]: set(row["EXTRAS"]) for row in declared}
    for row in run1:
        if row["REQUIRES_PYTHON"]:
            assert Version(target["python_full_version"]) in Requirement(
                "python" + row["REQUIRES_PYTHON"]
            ).specifier, "Python target violates package compatibility"
    edges = []
    seen = set()
    changed = True
    while changed:
        changed = False
        for row in run1:
            for text_requirement in row["REQUIRES_DIST"]:
                requirement = Requirement(text_requirement)
                contexts = ["", *sorted(extras.get(row["DISTRIBUTION"], set()))]
                applies = requirement.marker is None or any(
                    requirement.marker.evaluate({**target, "extra": extra})
                    for extra in contexts
                )
                if not applies:
                    continue
                name = canonicalize_name(requirement.name)
                resolved = name in locked and Version(locked[name]["VERSION"]) in requirement.specifier
                key = (row["DISTRIBUTION"], text_requirement)
                if key not in seen:
                    edges.append({
                        "FROM": row["DISTRIBUTION"], "TO": name,
                        "REQUIREMENT": text_requirement,
                        "TARGET_MARKER_APPLIES": True, "RESOLVED": resolved,
                    })
                    seen.add(key)
                current = extras.setdefault(name, set())
                before = len(current)
                current.update(requirement.extras)
                changed |= len(current) != before
    lock = lock_text(run1)
    return lock, {
        "PACKAGE_AUTHORITY": "pip requirements.txt",
        "RESOLVER": {"NAME": "pip", "VERSION": first["pip_version"]},
        "RESOLVER_FLAGS": [
            "--isolated", "install", "--dry-run", "--ignore-installed",
            "--only-binary=:all:", "--python-version", "3.11.14",
            "--platform", "manylinux2014_x86_64", "--implementation", "cp", "--abi", "cp311",
            "--index-url", "https://pypi.org/simple", "-r", "apps/union-eyes/backend/requirements.txt",
        ],
        "TARGET": {"PYTHON": "3.11.14", "EXACT_PATCH": "3.11.14",
                   "PLATFORM": "manylinux2014_x86_64", "IMPLEMENTATION": "cp", "ABI": "cp311"},
        "RESOLVER_MARKER_ENVIRONMENT": first["environment"],
        "CROSS_TARGET_MARKER_EVALUATION": "Host pip marker environment differs; explicit Linux 3.11 transitive validation recorded separately",
        "PACKAGE_INDEX_ACCESS_OCCURRED": True,
        "INDEX": "https://pypi.org/simple",
        "REQUIREMENTS_SHA256": sha((BACKEND / "requirements.txt").read_bytes()),
        "DECLARED_DIRECT_DEPENDENCIES": sorted(declared, key=lambda row: row["DISTRIBUTION"]),
        "LOCKED_DISTRIBUTIONS": run1,
        "TRANSITIVE_REQUIREMENT_EDGES": sorted(edges, key=lambda row: (row["FROM"], row["REQUIREMENT"])),
        "TARGET_REQUIREMENTS_UNRESOLVED": [row for row in edges if not row["RESOLVED"]],
        "RUN_1_LOCK_DIGEST": sha(lock.encode()),
        "RUN_2_LOCK_DIGEST": sha(lock_text(run2).encode()),
        "ALL_LOCK_DIGESTS_MATCH": True,
    }


def self_test():
    fake = {"install": [{
        "metadata": {"name": "demo", "version": "1.0"},
        "requested": True,
        "download_info": {"url": "https://files.pythonhosted.org/demo.whl",
                          "archive_info": {"hashes": {"sha256": "a" * 64}}},
    }]}
    assert normalize(fake)[0]["ARTIFACT_SHA256"] == "a" * 64
    assert "--hash=sha256:" in lock_text(normalize(fake))
    bad = json.loads(json.dumps(fake))
    bad["install"].append(bad["install"][0])
    try:
        normalize(bad)
    except AssertionError:
        pass
    else:
        raise AssertionError("Duplicate distribution accepted")
    assert Requirement("demo>=1").specifier.contains("1.0")
    assert not Requirement("demo>=2").specifier.contains("1.0")
    print("PASS: exact artifact hashes, duplicate rejection and compatibility constraints.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--run1", type=Path)
    parser.add_argument("--run2", type=Path)
    parser.add_argument("--evidence", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
    else:
        assert args.run1 and args.run2 and args.evidence
        lock, evidence = build(
            json.loads(args.run1.read_text(encoding="utf-8")),
            json.loads(args.run2.read_text(encoding="utf-8")),
        )
        evidence_text = json.dumps(evidence, indent=2, sort_keys=True) + "\n"
        formatted = subprocess.run([
            "node", "--input-type=module", "--eval",
            "import {format,resolveConfig} from 'prettier';let input='';"
            "for await(const c of process.stdin)input+=c;"
            "process.stdout.write(await format(input,{...await resolveConfig('package.json'),parser:'json'}));"
        ], input=evidence_text, text=True, encoding="utf-8", capture_output=True, cwd=ROOT, check=True)
        evidence_text = formatted.stdout
        if args.check:
            assert (BACKEND / "requirements.lock").read_text(encoding="utf-8") == lock
            assert args.evidence.read_text(encoding="utf-8") == evidence_text
        else:
            (BACKEND / "requirements.lock").write_text(lock, encoding="utf-8", newline="\n")
            args.evidence.write_text(evidence_text, encoding="utf-8", newline="\n")
        print(json.dumps({
            "LOCKED": len(evidence["LOCKED_DISTRIBUTIONS"]),
            "DIRECT": len(evidence["DECLARED_DIRECT_DEPENDENCIES"]),
            "TRANSITIVE": sum(not row["DIRECT"] for row in evidence["LOCKED_DISTRIBUTIONS"]),
            "LOCK_DIGEST": evidence["RUN_1_LOCK_DIGEST"],
            "TARGET_REQUIREMENTS_UNRESOLVED": evidence["TARGET_REQUIREMENTS_UNRESOLVED"],
        }, indent=2))
